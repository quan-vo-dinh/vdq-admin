// Ship the selected SVG paths with the app; never fetch brand logos at runtime.
function simple(icon: SimpleIcon) {
  const monochrome = ["000000", "FFFFFF", "181717", "111111"].includes(icon.hex.toUpperCase());
  return function BrandIcon({ className, ...props }: SVGProps<SVGSVGElement>) {
    return (
      <svg
        {...props}
        viewBox="0 0 24 24"
        fill={monochrome ? "currentColor" : `#${icon.hex}`}
        className={cn(monochrome && "text-foreground", className)}
      >
        <path d={icon.path} />
      </svg>
    );
  };
}
